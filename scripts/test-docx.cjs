const fs = require("fs");
const path = require("path");
const docx = require("docx");

const {
  Document,
  Packer,
  Paragraph,
  TextRun,
  HeadingLevel,
  TableOfContents,
  Header,
  Footer,
  PageNumber,
  NumberFormat,
  AlignmentType,
  BorderStyle,
  convertInchesToTwip
} = docx;

// Sample full document data (combining Stage 1 research + Stage 2 outline + Stage 3 sections)
